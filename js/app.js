document.addEventListener("DOMContentLoaded", () => {
    const countrySel = document.getElementById("country-select");
    const clubSel = document.getElementById("club-select");

    if (!countrySel || !clubSel) return;

    countrySel.innerHTML = '<option value="">-- Оберіть країну --</option>';
    Object.keys(leagueData).forEach(code => {
        const opt = document.createElement("option");
        opt.value = code;
        opt.innerText = leagueData[code].name;
        countrySel.appendChild(opt);
    });

    clubSel.innerHTML = '<option value="">-- Спочатку оберіть країну --</option>';

    countrySel.addEventListener("change", (e) => {
        const countryCode = e.target.value;
        clubSel.innerHTML = "";

        if (!countryCode || !leagueData[countryCode]) {
            clubSel.innerHTML = '<option value="">-- Спочатку оберіть країну --</option>';
            return;
        }

        const defaultOpt = document.createElement("option");
        defaultOpt.value = "";
        defaultOpt.innerText = "-- Оберіть клуб --";
        clubSel.appendChild(defaultOpt);

        leagueData[countryCode].clubs.forEach(c => {
            const opt = document.createElement("option");
            opt.value = c.id;
            opt.innerText = c.name;
            clubSel.appendChild(opt);
        });
    });

    clubSel.addEventListener("change", (e) => {
        const countryCode = countrySel.value;
        const clubId = e.target.value;
        if (!countryCode || !clubId) return;

        const club = leagueData[countryCode].clubs.find(c => c.id === clubId);
        if (!club) return;

        // Заповнення полів інтерфейсу проєкту (згідно з існуючою версткою)
        const nameEl = document.getElementById("club-name");
        const leagueEl = document.getElementById("club-league-info");
        const rankEl = document.getElementById("club-rank");
        const coachEl = document.getElementById("coach-name");
        const staffEl = document.getElementById("staff-members");
        const reasoningEl = document.getElementById("tactical-reasoning");
        const countEl = document.getElementById("squad-count");

        if (nameEl) nameEl.innerText = club.name;
        if (leagueEl) leagueEl.innerText = club.leagueDetails;
        if (rankEl) rankEl.innerText = club.rank;
        if (coachEl) coachEl.innerText = club.coach;
        if (staffEl) staffEl.innerText = club.staff;
        if (reasoningEl) reasoningEl.innerText = `${club.reasoning} \n\n[Аналітика та схема]: ${club.analytics} (${club.formation})`;
        if (countEl) countEl.innerText = club.players.length;
    });
});
